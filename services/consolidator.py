"""
Pure-Python Document & Code Consolidator
Supports:
- Markdown (.md) with syntax highlighting fences and Table of Contents
- Plain Text (.txt)
- Pure-Python PDF generation (ReportLab) with zero LibreOffice/Word dependencies
- Native PDF merging via pypdf
"""
import io
import os
from typing import List, Tuple, Any, Dict
from pypdf import PdfWriter, PdfReader
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Preformatted, PageBreak
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.pdfgen import canvas


class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to add accurate page numbers and headers/footers."""
    def __init__(self, *args, **kwargs):
        canvas.Canvas.__init__(self, *args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)

    def draw_page_number(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor("#718096"))
        
        # Header line
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(54, 750, 558, 750)
        self.drawString(54, 755, "DocuStream Consolidated Document")
        
        # Footer
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(558, 40, page_str)
        self.drawString(54, 40, "Generated by DocuStream")
        self.line(54, 52, 558, 52)
        self.restoreState()


class DocumentConsolidator:
    """Consolidates text, code, and PDF files into structured documents."""

    CODE_EXTENSIONS = {
        '.py': 'python', '.js': 'javascript', '.jsx': 'javascript',
        '.ts': 'typescript', '.tsx': 'typescript', '.html': 'html',
        '.css': 'css', '.json': 'json', '.sql': 'sql', '.java': 'java',
        '.c': 'c', '.cpp': 'cpp', '.h': 'c', '.hpp': 'cpp',
        '.cs': 'csharp', '.go': 'go', '.rs': 'rust', '.sh': 'bash',
        '.yaml': 'yaml', '.yml': 'yaml', '.toml': 'toml', '.xml': 'xml',
        '.md': 'markdown', '.txt': 'text'
    }

    @classmethod
    def read_file_content(cls, file_obj: Any) -> Tuple[str, bool]:
        """
        Safely reads text content from a file-like object or path.
        Returns (content, is_binary_pdf).
        """
        filename = getattr(file_obj, 'name', 'unnamed')
        ext = os.path.splitext(filename)[1].lower()

        # Handle pointer reset
        if hasattr(file_obj, 'seek'):
            file_obj.seek(0)

        # PDF handling: extract real text via pypdf
        if ext == '.pdf':
            try:
                reader = PdfReader(file_obj)
                pages_text = []
                for i, page in enumerate(reader.pages):
                    extracted = page.extract_text() or ""
                    pages_text.append(f"--- [Page {i+1}] ---\n{extracted.strip()}")
                return "\n\n".join(pages_text), True
            except Exception as e:
                return f"[Could not extract text from PDF {filename}: {str(e)}]", True

        # Text/Code handling
        if hasattr(file_obj, 'read'):
            raw = file_obj.read()
            if isinstance(raw, str):
                return raw, False
            try:
                return raw.decode('utf-8'), False
            except UnicodeDecodeError:
                # Fallback to UTF-8 with replacement for corrupt characters, not latin-1
                return raw.decode('utf-8', errors='replace'), False

        return "", False

    @classmethod
    def merge_to_markdown(cls, file_list: List[Any], include_toc: bool = True) -> str:
        """Merges code and text files into a clean Markdown document with Table of Contents."""
        toc_lines = ["# Table of Contents\n"]
        body_sections = []

        for i, file_obj in enumerate(file_list, start=1):
            filename = getattr(file_obj, 'name', f'File_{i}')
            ext = os.path.splitext(filename)[1].lower()
            lang = cls.CODE_EXTENSIONS.get(ext, '')
            content, is_pdf = cls.read_file_content(file_obj)

            anchor = f"file-{i}-{filename.lower().replace('.', '-').replace(' ', '-')}"
            toc_lines.append(f"{i}. [{filename}](#{anchor})")

            section = [
                f'<a id="{anchor}"></a>',
                f"## {i}. {filename}\n",
            ]
            if is_pdf:
                section.append("*Extracted text from PDF document:*\n")

            if lang:
                section.append(f"```{lang}\n{content}\n```\n")
            else:
                section.append(f"```text\n{content}\n```\n")

            body_sections.append("\n".join(section))

        doc = []
        if include_toc:
            doc.append("\n".join(toc_lines))
            doc.append("\n---\n")
        doc.append("\n\n".join(body_sections))
        return "\n".join(doc)

    @classmethod
    def merge_to_text(cls, file_list: List[Any]) -> str:
        """Merges files into a structured plain text document."""
        sections = []
        for i, file_obj in enumerate(file_list, start=1):
            filename = getattr(file_obj, 'name', f'File_{i}')
            content, _ = cls.read_file_content(file_obj)
            header = f"\n{'=' * 60}\nFILE {i}: {filename}\n{'=' * 60}\n"
            sections.append(f"{header}\n{content}\n")
        return "\n".join(sections)

    @classmethod
    def create_pdf_from_text(cls, title: str, text_content: str, is_code: bool = True) -> io.BytesIO:
        """Creates a styled PDF from raw text or code using ReportLab (Pure Python)."""
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            leftMargin=54,
            rightMargin=54,
            topMargin=54,
            bottomMargin=54
        )

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            'DocTitle',
            parent=styles['Heading1'],
            fontName='Helvetica-Bold',
            fontSize=16,
            leading=20,
            textColor=colors.HexColor("#2D3748"),
            spaceAfter=12
        )
        code_style = ParagraphStyle(
            'CodeBlock',
            fontName='Courier',
            fontSize=8,
            leading=10,
            textColor=colors.HexColor("#1A202C")
        )

        story = [Paragraph(title, title_style), Spacer(1, 10)]

        # Wrap text nicely in code style or normal paragraph
        # Truncate overly long lines to avoid margin clipping
        max_line_len = 95
        formatted_lines = []
        for line in text_content.split('\n'):
            while len(line) > max_line_len:
                formatted_lines.append(line[:max_line_len])
                line = line[max_line_len:]
            formatted_lines.append(line)

        formatted_text = "\n".join(formatted_lines)
        story.append(Preformatted(formatted_text, code_style))

        doc.build(story, canvasmaker=NumberedCanvas)
        buffer.seek(0)
        return buffer

    @classmethod
    def merge_to_pdf(cls, file_list: List[Any]) -> io.BytesIO:
        """
        Consolidates files into a single unified PDF:
        - Text/code/markdown files are rendered to PDF via ReportLab.
        - Existing PDF files are appended page-by-page via pypdf.
        """
        writer = PdfWriter()

        for file_obj in file_list:
            filename = getattr(file_obj, 'name', 'Document')
            ext = os.path.splitext(filename)[1].lower()

            if hasattr(file_obj, 'seek'):
                file_obj.seek(0)

            if ext == '.pdf':
                # Direct PDF merge
                reader = PdfReader(file_obj)
                for page in reader.pages:
                    writer.add_page(page)
            else:
                # Render code/text to PDF via ReportLab
                content, _ = cls.read_file_content(file_obj)
                pdf_stream = cls.create_pdf_from_text(f"File: {filename}", content, is_code=True)
                reader = PdfReader(pdf_stream)
                for page in reader.pages:
                    writer.add_page(page)

        output = io.BytesIO()
        writer.write(output)
        output.seek(0)
        return output

    @classmethod
    def consolidate(cls, file_list: List[Any], output_format: str) -> Tuple[bytes, str]:
        """
        Main consolidation entrypoint.
        Returns: (data_bytes, mime_type)
        """
        fmt = output_format.upper()
        if fmt == "MD" or fmt == "MARKDOWN":
            md_str = cls.merge_to_markdown(file_list, include_toc=True)
            return md_str.encode('utf-8'), "text/markdown"
        elif fmt == "TXT" or fmt == "TEXT":
            txt_str = cls.merge_to_text(file_list)
            return txt_str.encode('utf-8'), "text/plain"
        elif fmt == "PDF":
            pdf_buffer = cls.merge_to_pdf(file_list)
            return pdf_buffer.getvalue(), "application/pdf"
        else:
            raise ValueError(f"Unsupported output format: {output_format}. Choose MD, TXT, or PDF.")
